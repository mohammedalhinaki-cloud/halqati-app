/*
 * Builds the app's ONE canonical Quran dataset from the pinned sources in
 * data/sources/ and writes:
 *   • lib/quran-data.js            — the module every part of the app imports
 *   • data/quran.json              — the same dataset as plain JSON (scripts/CI)
 *   • data/quran-verification.json — the full cross-source verification report
 *
 * The build ABORTS (non-zero exit) if any check fails: wrong ayah count, an
 * ayah out of range, a page mismatch between the two independent sources, a
 * mis-ordered layout, or a source file whose checksum is not the pinned one.
 * Nothing here ever guesses an ayah number or a range.
 *
 * Run: npm run gen      (re-pin sources after a deliberate source update: --pin)
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { buildQuranData, readLock, sha256, SRC_DIR, ROOT } from './quran-checks.mjs';

const PIN = process.argv.includes('--pin');

/* --- re-pin mode: record the checksums of the sources currently on disk ---- */
if (PIN) {
  const files = {
    tanzil: 'tanzil-quran-data.xml',
    qcf4Index: 'qcf4-index.json',
    qcf4Verses: 'qcf4-verses.json',
    apiAnchors: 'quran-com-api-anchors.json',
    pageModelNotes: 'page-model-notes.json',
  };
  const sources = {};
  for (const [k, f] of Object.entries(files)) sources[k] = { file: `data/sources/${f}`, sha256: sha256(path.join(SRC_DIR, f)) };
  const sampleDir = path.join(SRC_DIR, 'qcf4-pages-sample');
  if (fs.existsSync(sampleDir))
    for (const f of fs.readdirSync(sampleDir).filter((x) => /^\d+\.json$/.test(x)).sort())
      sources[`page${f.replace('.json', '')}`] = {
        file: `data/sources/qcf4-pages-sample/${f}`,
        sha256: sha256(path.join(sampleDir, f)),
      };
  const lock = {
    note: 'sha256 of every pinned Quran source. A mismatch aborts `npm run gen` until this file is updated after a verified source change.',
    updated: new Date().toISOString().slice(0, 10),
    sources,
  };
  fs.writeFileSync(path.join(SRC_DIR, 'sources.lock.json'), JSON.stringify(lock, null, 2) + '\n');
  console.log(`pinned ${Object.keys(sources).length} source files -> data/sources/sources.lock.json`);
  process.exit(0);
}

const lock = readLock();
const { data, report } = buildQuranData({ lock });

/* --- print the verification table ---------------------------------------- */
let bad = 0;
console.log('\nQuran data checks (sources → data):');
for (const c of report.checks) {
  if (!c.ok) bad++;
  const mark = c.ok ? '✓' : '✗';
  console.log(`  ${mark} ${c.name}${c.detail ? (c.ok ? ` — ${c.detail}` : `\n      ↳ ${c.detail}`) : ''}`);
}
if (bad) {
  console.error(`\nBUILD ABORTED — ${bad} check(s) failed. No data was written.\n`);
  process.exit(1);
}

/* --- write the artifacts -------------------------------------------------- */
const body = JSON.stringify(data);
fs.writeFileSync(
  path.join(ROOT, 'lib', 'quran-data.js'),
  '/* GENERATED by scripts/build-quran-data.mjs — DO NOT EDIT, do not hand-edit ayah data.\n' +
    '   Sources + sha256: data/sources/, verification: data/quran-verification.json */\n' +
    `export default ${body};\n`
);
fs.writeFileSync(path.join(ROOT, 'data', 'quran.json'), body + '\n');

const verification = {
  generatedBy: 'scripts/build-quran-data.mjs',
  dataSha256: crypto.createHash('sha256').update(body).digest('hex'),
  totals: {
    surahs: data.surahs.length,
    ayahs: data.ayahQ.length,
    pages: data.meta.pages,
    quarters: data.meta.totalQuarters,
    quarterSumOfAyahSpans:
      data.ayahQ.reduce((acc, q, i) => acc + (i + 1 < data.ayahQ.length ? data.ayahQ[i + 1] - q : 0), 0) +
      (data.meta.totalQuarters - data.ayahQ[data.ayahQ.length - 1]),
  },
  sources: data.meta.sources,
  checks: report.checks,
};
fs.writeFileSync(path.join(ROOT, 'data', 'quran-verification.json'), JSON.stringify(verification, null, 2) + '\n');

console.log(`\nOK -> lib/quran-data.js (${data.surahs.length} surahs, ${data.ayahQ.length} ayahs, ${data.meta.totalQuarters} quarter-faces)`);
console.log(`OK -> data/quran.json + data/quran-verification.json (${report.checks.length} checks passed)`);
